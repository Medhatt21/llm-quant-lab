"""Post-experiment report generation.

This module orchestrates the end-to-end scientist report generation
after an experiment completes.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any

from ..db import get_experiment_with_details, get_session, log_scientist_report
from .payload_builder import build_scientist_payload, load_paper_notes
from .scientist_client import LLMResponse, get_scientist_client

logger = logging.getLogger(__name__)


def generate_scientist_report(
    experiment_id: int,
    paper_ids: list[str] | None = None,
    db_url: str | None = None,
    save_to_file: bool = True,
    output_dir: str = "reports",
) -> dict[str, Any]:
    """Generate a scientist report for an experiment.
    
    This function:
    1. Queries the database for experiment data
    2. Loads paper notes if specified
    3. Builds the prompt payload
    4. Calls the scientist LLM
    5. Parses the response
    6. Stores the report in the database
    7. Optionally saves to a file
    
    Args:
        experiment_id: ID of the experiment to analyze
        paper_ids: Optional list of paper IDs for context
        db_url: Optional database URL
        save_to_file: Whether to save the report to a file
        output_dir: Directory for output files
        
    Returns:
        Dictionary with report details
    """
    logger.info(f"Generating scientist report for experiment {experiment_id}")
    
    # Get database session
    session = get_session(db_url)
    
    try:
        # Get experiment data
        experiment_data = get_experiment_with_details(session, experiment_id)
        
        if not experiment_data:
            raise ValueError(f"Experiment {experiment_id} not found")
        
        # Load paper notes
        paper_notes = []
        if paper_ids:
            # Try loading from files first
            paper_notes = load_paper_notes(paper_ids)
            
            # If not found, try database
            if not paper_notes:
                from .payload_builder import load_paper_notes_from_db
                paper_notes = load_paper_notes_from_db(session, paper_ids)
        
        # Build payload
        payload = build_scientist_payload(experiment_data, paper_notes)
        
        # Get LLM client
        client = get_scientist_client()
        
        # Call LLM
        logger.info("Calling scientist LLM...")
        response = client.call_with_retry(
            prompt=payload["user_prompt"],
            system_prompt=payload["system_prompt"],
            temperature=payload.get("temperature", 0.0),
            max_tokens=payload.get("max_tokens", 4000),
        )
        
        # Parse response
        parsed = parse_scientist_response(response.content)
        
        # Log to database
        report = log_scientist_report(
            session=session,
            experiment_id=experiment_id,
            prompt_payload_json={
                "system_prompt": payload["system_prompt"],
                "user_prompt": payload["user_prompt"][:10000],  # Truncate for storage
                "temperature": payload.get("temperature"),
                "max_tokens": payload.get("max_tokens"),
            },
            report_markdown=response.content,
            llm_model=response.model,
            llm_provider=_extract_provider(client),
            summary=parsed.get("summary"),
            pass_fail=parsed.get("pass_fail"),
            confidence_score=parsed.get("confidence_score"),
            reasoning_tags=parsed.get("reasoning_tags"),
            key_findings=parsed.get("key_findings"),
            suggested_experiments=parsed.get("suggested_experiments"),
            prompt_tokens=response.prompt_tokens,
            completion_tokens=response.completion_tokens,
            total_tokens=response.total_tokens,
        )
        
        # Save to file
        if save_to_file:
            output_path = Path(output_dir) / f"experiment_{experiment_id}.md"
            output_path.parent.mkdir(parents=True, exist_ok=True)
            
            with open(output_path, "w") as f:
                f.write(f"# Scientist Report: Experiment {experiment_id}\n\n")
                f.write(f"**Model**: {experiment_data['experiment'].get('model_name', 'unknown')}\n")
                f.write(f"**Generated by**: {response.model}\n")
                f.write(f"**Pass/Fail**: {parsed.get('pass_fail', 'unknown')}\n\n")
                f.write("---\n\n")
                f.write(response.content)
            
            logger.info(f"Report saved to {output_path}")
        
        return {
            "report_id": report.id,
            "experiment_id": experiment_id,
            "report_markdown": response.content,
            "summary": parsed.get("summary"),
            "pass_fail": parsed.get("pass_fail"),
            "key_findings": parsed.get("key_findings"),
            "suggested_experiments": parsed.get("suggested_experiments"),
            "llm_model": response.model,
            "tokens_used": response.total_tokens,
        }
        
    finally:
        session.close()


def parse_scientist_response(content: str) -> dict[str, Any]:
    """Parse the scientist LLM response to extract structured information.
    
    Args:
        content: Raw markdown response from LLM
        
    Returns:
        Dictionary with extracted fields
    """
    result: dict[str, Any] = {
        "summary": None,
        "pass_fail": "unknown",
        "confidence_score": None,
        "reasoning_tags": [],
        "key_findings": [],
        "suggested_experiments": [],
    }
    
    # Extract summary (first paragraph after executive summary)
    summary_match = re.search(
        r"(?:Executive Summary|Summary)\s*\n+(.+?)(?:\n\n|\n#)",
        content,
        re.IGNORECASE | re.DOTALL,
    )
    if summary_match:
        result["summary"] = summary_match.group(1).strip()[:500]
    
    # Extract pass/fail judgment
    pass_fail_patterns = [
        (r"\*\*(?:Status|Judgment|Verdict)\*\*:\s*\*?\*?(PASS|FAIL|INCONCLUSIVE)", 1),
        (r"(?:Status|Judgment|Verdict):\s*\*?\*?(PASS|FAIL|INCONCLUSIVE)", 1),
        (r"\*\*(PASS|FAIL|INCONCLUSIVE)\*\*", 1),
    ]
    
    for pattern, group in pass_fail_patterns:
        match = re.search(pattern, content, re.IGNORECASE)
        if match:
            result["pass_fail"] = match.group(group).lower()
            break
    
    # Extract key findings
    findings_section = re.search(
        r"(?:Key Findings|Findings)\s*\n+((?:[-*\d]\.?\s+.+\n?)+)",
        content,
        re.IGNORECASE,
    )
    if findings_section:
        findings = re.findall(r"[-*\d]\.?\s+(.+)", findings_section.group(1))
        result["key_findings"] = [f.strip() for f in findings[:10]]
    
    # Extract suggested experiments
    suggestions_section = re.search(
        r"(?:Suggested|Next|Future)\s*(?:Experiments?|Steps?)\s*\n+((?:[-*\d]\.?\s+.+\n?)+)",
        content,
        re.IGNORECASE,
    )
    if suggestions_section:
        suggestions = re.findall(r"[-*\d]\.?\s+(.+)", suggestions_section.group(1))
        result["suggested_experiments"] = [s.strip() for s in suggestions[:10]]
    
    # Extract reasoning tags
    tags = []
    
    # Look for specific patterns that indicate reasoning categories
    tag_patterns = [
        (r"outlier", "outlier_analysis"),
        (r"accuracy\s+(?:drop|degradation|loss)", "accuracy_impact"),
        (r"latency\s+(?:improvement|reduction)", "latency_improvement"),
        (r"memory\s+(?:reduction|savings)", "memory_savings"),
        (r"failure\s+mode", "failure_mode_identified"),
        (r"novel\s+insight", "novel_insight"),
        (r"confirms?\s+(?:hypothesis|expectation)", "hypothesis_confirmed"),
        (r"contradict", "contradiction_found"),
        (r"layer[\s-]wise", "layer_analysis"),
        (r"calibration", "calibration_analysis"),
    ]
    
    for pattern, tag in tag_patterns:
        if re.search(pattern, content, re.IGNORECASE):
            tags.append(tag)
    
    result["reasoning_tags"] = tags
    
    return result


def _extract_provider(client: Any) -> str:
    """Extract the provider name from the client."""
    if hasattr(client, "base_url"):
        base_url = client.base_url
        if "openai" in base_url:
            return "openai"
        elif "anthropic" in base_url:
            return "anthropic"
        elif "azure" in base_url:
            return "azure"
    return "unknown"


def regenerate_report(
    experiment_id: int,
    paper_ids: list[str] | None = None,
    db_url: str | None = None,
) -> dict[str, Any]:
    """Regenerate a scientist report for an experiment.
    
    This is a convenience wrapper that always generates a new report,
    even if one already exists.
    
    Args:
        experiment_id: Experiment ID
        paper_ids: Optional paper IDs
        db_url: Optional database URL
        
    Returns:
        Report details
    """
    return generate_scientist_report(
        experiment_id=experiment_id,
        paper_ids=paper_ids,
        db_url=db_url,
        save_to_file=True,
    )


def batch_generate_reports(
    experiment_ids: list[int],
    paper_ids: list[str] | None = None,
    db_url: str | None = None,
) -> list[dict[str, Any]]:
    """Generate reports for multiple experiments.
    
    Args:
        experiment_ids: List of experiment IDs
        paper_ids: Optional paper IDs to use for all
        db_url: Optional database URL
        
    Returns:
        List of report details
    """
    results = []
    
    for exp_id in experiment_ids:
        try:
            result = generate_scientist_report(
                experiment_id=exp_id,
                paper_ids=paper_ids,
                db_url=db_url,
            )
            results.append(result)
        except Exception as e:
            logger.error(f"Failed to generate report for experiment {exp_id}: {e}")
            results.append({
                "experiment_id": exp_id,
                "error": str(e),
            })
    
    return results
